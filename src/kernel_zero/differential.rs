//! The Kernel-0 differential test.
//!
//! For each program below (a small hand-written edge-case corpus plus
//! `super::corpus`'s deterministic generated corpus), this:
//! 1. Writes the program's `.spx` source to a temp file.
//! 2. Independently `crate::parse`s and `hir::resolve`s that same source
//!    (exactly as `super::kernel_zero.rs`'s own admission tests already do),
//!    derives and replays `super::reify::BoundTranslation` from the exact
//!    source and entry, then evaluates the replayed term with
//!    `super::eval::eval_program` -- the from-scratch
//!    reference side.
//! 3. Drives the compiler's real interpreter backend through its ordinary
//!    public entry point, `crate::interpreter::interpret` (the same
//!    function `tests/interpreter_v1.rs`'s own golden-envelope tests call)
//!    -- never by constructing an `Evaluator` or calling `evaluate`/
//!    `combine` directly.
//! 4. Compares the two outcomes and, on any disagreement, records it (never
//!    panicking mid-corpus) so the full set of disagreements -- not just the
//!    first -- is visible in one test failure.
//!
//! Per this task's explicit instruction: a disagreement found here must
//! never be papered over by adjusting the reference interpreter to match
//! the compiler. If this test ever goes red, read the failure message's
//! embedded source and arguments, decide from
//! `docs/SEMANTIC-KERNEL-V1.md`/`docs/RFC-0001.md` which side is wrong, and
//! report it -- do not edit this file's comparison logic to silence it.

use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};

