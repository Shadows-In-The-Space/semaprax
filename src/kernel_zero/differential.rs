#[test]
fn rung_one_candidate_reifies_and_matches_reference_and_compiler_interpreters() {
    assert!(RUNG_ONE_SOURCE.len() < 4 * 1024);
    let ast = crate::parse(RUNG_ONE_SOURCE, "kernel-zero-rung-one.spx").unwrap();
    let hir = hir::resolve(&ast).unwrap();
    for id in [
        "policy.role-known",
        "policy.operation-known",
        "policy.write-operation",
        "policy.units-known",
        "policy.classify",
        "app.main",
    ] {
        assert!(
            super::reifies_into_kernel_zero(&hir, &DeclarationId::new(id)),
            "rung-1 declaration {id} left the Kernel-0 fragment"
        );
    }
    let entry = DeclarationId::new("policy.classify");
    let binding = BoundTranslation::derive(RUNG_ONE_SOURCE, &entry).unwrap();
    let program = binding.replay(RUNG_ONE_SOURCE, &entry).unwrap();
    let function = program.function(&entry).unwrap();
    let fixtures = rung_one_samples();
    assert_eq!(fixtures.len(), 14, "the decision-table corpus changed");
    for (arguments, expected) in fixtures {
        assert_eq!(
            eval_program(program, function, &arguments),
            Ok(Value::Int(expected)),
            "rung-1 decision table disagreed for {arguments:?}"
        );
    }

    let case = rung_one_case();
    let mut failures = Vec::new();
    let mut total = 0usize;
    run_case(&case, &mut failures, &mut total);
    assert_eq!(total, 14, "the focused interpreter corpus changed");
    assert!(
        failures.is_empty(),
        "rung-1 candidate disagreed with the compiler interpreter:\n{}",
        failures.join("\n---\n")
    );
}

/// Hand-written edge cases the task calls out explicitly: overflow,
/// division/remainder by zero, short-circuit laziness, evaluation order,
/// and the documented `bool == bool`/`bool != bool` extension (see
/// `super::corpus`'s doc comment on the same gap).
fn hand_written_cases() -> Vec<Case> {
    let module = |body: &str| {
        format!(
            "module test.kernel_zero_hand_written;\n\n\
             @id(\"app.main\")\nfn main() -> i64 {{ 0 }}\n\n\
             @id(\"app.entry\")\nfn entry() -> i64\n{{\n    {body}\n}}\n"
        )
    };

    let mut cases = vec![
        int_case(
            &module("9223372036854775807 + 1"),
            "app.entry",
            vec![vec![]],
        ),
        int_case(
            &module("(-9223372036854775807) - 2"),
            "app.entry",
            vec![vec![]],
        ),
        int_case(
            &module("4611686018427387904 * 2"),
            "app.entry",
            vec![vec![]],
        ),
        int_case(&module("1 / 0"), "app.entry", vec![vec![]]),
        int_case(&module("1 % 0"), "app.entry", vec![vec![]]),
        int_case(
            &module("(-9223372036854775807 - 1) / -1"),
            "app.entry",
            vec![vec![]],
        ),
        int_case(
            &module("(-9223372036854775807 - 1) % -1"),
            "app.entry",
            vec![vec![]],
        ),
        int_case(
            &module("-(-9223372036854775807 - 1)"),
            "app.entry",
            vec![vec![]],
        ),
        // `if`'s untaken branch is never reduced at all -- picking the safe
        // branch must never fault, even though the other branch would.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry(pick: bool) -> i64\n\
                     {\n    if pick { 1 / 0 } else { 42 }\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![Value::Bool(false)], vec![Value::Bool(true)]],
        },
        // Lazy boolean operands execute only when required (`AGENTS.md`):
        // `false && <would-fault>` and `true || <would-fault>` must reduce
        // to a plain value, never a fault.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry() -> bool\n\
                     {\n    false && ((1 / 0) == 0)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry() -> bool\n\
                     {\n    true || ((1 / 0) == 0)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        // `bool == bool` / `bool != bool`: admitted by the real compiler and
        // by `reifies_into_kernel_zero`, not stated by the document's
        // typing table -- see the doc/report note.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry(a: bool, b: bool) -> bool\n\
                     {\n    a == b\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![
                vec![Value::Bool(true), Value::Bool(true)],
                vec![Value::Bool(true), Value::Bool(false)],
                vec![Value::Bool(false), Value::Bool(true)],
                vec![Value::Bool(false), Value::Bool(false)],
            ],
        },
        // Non-recursive call chain, three levels deep, with a
        // non-commutative operator so left-to-right call-argument
        // evaluation is actually distinguishable from any other order.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"test.base\")\nfn base(a: i64, b: i64) -> i64 { a - b }\n\n\
                     @id(\"test.mid\")\nfn mid(x: i64) -> i64 { base(x, 10) }\n\n\
                     @id(\"app.entry\")\nfn entry(n: i64) -> i64\n\
                     {\n    mid(n)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![
                vec![Value::Int(0)],
                vec![Value::Int(5)],
                vec![Value::Int(100)],
            ],
        },
        // The nested `let`/`if`/call/arithmetic shape
        // `docs/SEMANTIC-KERNEL-V1.md`'s "Rung 0 evidence" section hand-ran
        // across all three backends, driven here through the real
        // differential path rather than a hand-run CLI session.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"test.add\")\nfn add(left: i64, right: i64) -> i64 { left + right }\n\n\
                     @id(\"test.classify\")\nfn classify(value: i64) -> i64\n\
                     {\n    if value < 0 { 0 } else { 1 }\n}\n\n\
                     @id(\"app.entry\")\nfn entry() -> i64\n\
                     {\n    let sum = add(19, 23);\n    sum + classify(42)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        // Evaluation order determines *which* fault is observed when both
        // operands of a binary operator would fault: left-to-right means
        // the left operand's fault always wins, and the right operand is
        // never even reached (`eval_term`'s `let left_value = ...?;` before
        // `let right_value = ...?;`) -- not merely "a fault is produced",
        // which a right-to-left or eager-both-sides evaluator could also
        // satisfy while still disagreeing on *which* one. Each pair below
        // swaps which side faults, so a backend that got the direction
        // backwards would disagree on exactly one of the two, not both.
        int_case(&module("(1 / 0) + (5 % 0)"), "app.entry", vec![vec![]]),
        int_case(&module("(5 % 0) + (1 / 0)"), "app.entry", vec![vec![]]),
        int_case(&module("(1 / 0) - (5 % 0)"), "app.entry", vec![vec![]]),
        // Same evaluation-order requirement through a comparison operator,
        // not just `arith` -- `Cmp`'s reduction rule shares the same
        // left-to-right congruence context, per `Kernel0.lean`'s `Step`.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry() -> bool\n\
                     {\n    (1 / 0) < (5 % 0)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        // A fault in `&&`/`||`'s *left* operand must propagate regardless
        // of what the right operand is (or would be) -- distinct from the
        // `false && <would-fault>` / `true || <would-fault>` lazy-right-
        // operand cases above, which never exercise a faulting *left*
        // operand at all. Both sides here would fault differently
        // (`DivisionByZero` vs `RemainderByZero`), so the observed fault
        // also pins evaluation order, the same way the arithmetic pairs
        // above do.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry() -> bool\n\
                     {\n    ((1 / 0) == 0) && ((5 % 0) == 0)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"app.entry\")\nfn entry() -> bool\n\
                     {\n    ((1 / 0) == 0) || ((5 % 0) == 0)\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        // `i64::MIN * -1`: `mul`'s own boundary overflow, distinct from the
        // `add`/`sub` boundary cases above and from `div`/`mod`'s dedicated
        // `i64::MIN`/`-1` special case -- `checked_mul` must reject `2^63`
        // (one past `i64::MAX`) the same ordinary way it rejects any other
        // out-of-range product.
        int_case(
            &module("(-9223372036854775807 - 1) * -1"),
            "app.entry",
            vec![vec![]],
        ),
        // The boundary that must *not* fault: `i64::MIN` divided or
        // remaindered by plain `1` (not `-1`) is exactly representable, and
        // `i64::MAX` remaindered by `-1` is `0`. An implementation that
        // over-applies the `i64::MIN`/`-1` special case to any negative
        // divisor, or to `div`/`mod` generically, would wrongly fault here.
        int_case(
            &module("(-9223372036854775807 - 1) / 1"),
            "app.entry",
            vec![vec![]],
        ),
        int_case(
            &module("9223372036854775807 % -1"),
            "app.entry",
            vec![vec![]],
        ),
        // A helper's parameter and the caller's own `let` binding reuse the
        // literal name `x` -- the generator's fresh `gen_vN`/`pN`/`eN` names
        // never collide, so this exact shape (which a real de-Bruijn-index
        // or naive name-based substitution bug could confuse) never arises
        // by chance. `helper`'s `x` must resolve to its own parameter, never
        // leak into or capture the caller's `x`.
        Case {
            source: "module test.kernel_zero_hand_written;\n\n\
                     @id(\"app.main\")\nfn main() -> i64 { 0 }\n\n\
                     @id(\"test.helper\")\nfn helper(x: i64) -> i64 { x + 1 }\n\n\
                     @id(\"app.entry\")\nfn entry() -> i64\n\
                     {\n    let x = 100;\n    helper(x - 90) + x\n}\n"
                .to_owned(),
            entry_id: "app.entry".to_owned(),
            samples: vec![vec![]],
        },
        // 20 nested `let`s, each a fresh distinct name one level deeper --
        // a de-Bruijn shift/substitution stress case far deeper than
        // anything the generator's own `depth` budget typically reaches.
        // See `deep_shadow_let_chain`'s own doc comment: literal shadowing
        // (reusing an in-scope name) is rejected by the resolver
        // (`SPX-T209`), confirmed while developing this case.
        int_case(
            &module(&deep_shadow_let_chain(20)),
            "app.entry",
            vec![vec![]],
        ),
        // 20 nested `if`s, alternating which branch is live, where every
        // dead branch is a `1 / 0` that must never be reduced -- the
        // single-level "untaken branch never faults" case above stressed
        // once; this stresses the same invariant at depth.
        int_case(
            &module(&deep_if_liveness_chain(20)),
            "app.entry",
            vec![vec![]],
        ),
    ];
    cases.push(rung_one_case());
    cases
}

fn generated_cases() -> Vec<Case> {
    corpus::generated_corpus()
        .into_iter()
        .chain(corpus::adversarial_fault_corpus())
        .chain(corpus::adversarial_structure_corpus())
        .map(|program| Case {
            source: program.source,
            entry_id: program.entry_id,
            samples: program.samples,
        })
        .collect()
}

#[test]
fn reference_interpreter_agrees_with_the_compiler_over_the_kernel_zero_corpus() {
    let mut failures = Vec::new();
    let mut total = 0usize;

    let hand_written = hand_written_cases();
    let hand_written_count = hand_written.len();
    for case in &hand_written {
        run_case(case, &mut failures, &mut total);
    }

    let generated = generated_cases();
    let generated_count = generated.len();
    for case in &generated {
        run_case(case, &mut failures, &mut total);
    }

    if !failures.is_empty() {
        panic!(
            "kernel-0 differential test found {} disagreement(s) out of {total} comparisons \
             ({hand_written_count} hand-written + {generated_count} generated program(s), \
             seed {:#x}):\n\n{}",
            failures.len(),
            corpus::CORPUS_SEED,
            failures.join("\n---\n")
        );
    }
    println!(
        "kernel-0 differential test: {total} comparisons across {hand_written_count} \
         hand-written and {generated_count} generated program(s) (seed {:#x}), 0 disagreements",
        corpus::CORPUS_SEED
    );
}
