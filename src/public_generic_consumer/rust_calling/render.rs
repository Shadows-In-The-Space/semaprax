/// The two per-leaf-bound tests: exactly at
/// `src/public_generic_abi/boundary_profile.rs::MAX_BYTES_PER_LEAF` is
/// accepted, one byte over is rejected locally by the native provider before
/// any endpoint execution. Generated (not part of the fixed
/// [`ROUND_TRIP_BODY`] template) because the assertion on the returned
/// `Output` has to name that record's actual first field.
fn per_leaf_bound_tests_fn(output: &RecordShape) -> String {
    let first_output_field = output.fields[0].field_name();
    let mut out = String::new();
    out.push_str("#[test]\n");
    out.push_str("fn exactly_the_per_leaf_byte_bound_is_accepted() {\n");
    out.push_str(
        "    let mut provider =\n        Provider::open(TRUSTED_DESCRIPTOR_BYTES, TRUSTED_BINDING_BYTES).expect(\"open\");\n",
    );
    out.push_str("    let at_bound = input_with_first_field(vec![0x5a; MAX_BYTES_PER_LEAF]);\n");
    out.push_str(
        "    let output = provider.transform(at_bound).expect(\"transform at the exact bound\");\n",
    );
    let _ = writeln!(
        out,
        "    assert_eq!(output.{first_output_field}.len(), MAX_BYTES_PER_LEAF);"
    );
    out.push_str("    drop(provider);\n");
    out.push_str("    assert_eq!(diagnostics::live_allocations(), 0);\n");
    out.push_str("}\n\n");

    out.push_str("#[test]\n");
    out.push_str("fn one_byte_over_the_per_leaf_bound_is_rejected_locally() {\n");
    out.push_str(
        "    let mut provider =\n        Provider::open(TRUSTED_DESCRIPTOR_BYTES, TRUSTED_BINDING_BYTES).expect(\"open\");\n",
    );
    out.push_str(
        "    let over_bound = input_with_first_field(vec![0x5a; MAX_BYTES_PER_LEAF + 1]);\n",
    );
    out.push_str("    let error = provider.transform(over_bound).unwrap_err();\n");
    out.push_str("    assert!(matches!(error, Error::CapacityExceeded(_)));\n");
    out.push_str("    drop(provider);\n");
    out.push_str(
        "    assert_eq!(\n        diagnostics::live_allocations(),\n        0,\n        \"a locally rejected input must leave nothing allocated\"\n    );\n",
    );
    out.push_str("}\n");
    out
}

/// One numeric byte literal per generated file, twelve bytes a line so a
/// diff of two generated crates stays readable, matching
/// `public_generic_consumer::byte_literal`'s own convention.
fn byte_array_literal(bytes: &[u8]) -> String {
    let mut out = String::from("&[\n");
    for chunk in bytes.chunks(12) {
        out.push_str("    ");
        for byte in chunk {
            let _ = write!(out, "0x{byte:02x}, ");
        }
        out.push('\n');
    }
    out.push(']');
    out
}
