const DESCRIPTOR_HEADER: &str = r#"//! Generated by `semaprax::public_generic_consumer::rust_calling`. Embeds
//! the exact trusted descriptor and native-provider-binding bytes this
//! consumer was generated from, and this consumer's OWN independent replay
//! check -- bounded Descriptor-v1 parsing followed by an exact comparison of
//! all twelve named fields against these embedded constants -- run
//! BEFORE any native allocation. Independent of whatever replay the native
//! provider performs on its own side of the same `Provider::open` call: a
//! consumer that only trusted the native provider's answer would defeat the
//! point of an independently verified descriptor (issue #152).

use crate::error::Error;

"#;

const DESCRIPTOR_VERIFY: &str = r#"fn parse_descriptor_v1(bytes: &[u8]) -> Option<[&[u8]; 12]> {
    // The reference Descriptor v1 wire is twelve bounded UTF-8 frames. The
    // submitted bytes are never used to size an allocation or an index before
    // both the total bound and each individual frame bound are checked.
    if bytes.len() > 131_072 { return None; }
    let mut offset = 0usize;
    let mut fields = [&bytes[0..0]; 12];
    for field in 0..12usize {
        let prefix_end = offset.checked_add(8)?;
        let prefix = bytes.get(offset..prefix_end)?;
        let mut width = [0u8; 8];
        width.copy_from_slice(prefix);
        let length = usize::try_from(u64::from_le_bytes(width)).ok()?;
        if length > 65_536 { return None; }
        let end = prefix_end.checked_add(length)?;
        if end > bytes.len() { return None; }
        let content = &bytes[prefix_end..end];
        if std::str::from_utf8(content).is_err() { return None; }
        let expected = match field {
            0 => Some(b"semaprax.public-generic-descriptor.v1".as_slice()),
            1 => Some(b"semaprax.public-generic-boundary-profile.v1".as_slice()),
            2 => Some(b"semaprax.public-generic-type-grammar.v1".as_slice()),
            _ => None,
        };
        if expected.is_some_and(|version| content != version) { return None; }
        fields[field] = content;
        offset = end;
    }
    (offset == bytes.len()).then_some(fields)
}

fn descriptor_fields_replay(candidate: &[u8], trusted: &[u8]) -> bool {
    let (Some(candidate), Some(trusted)) =
        (parse_descriptor_v1(candidate), parse_descriptor_v1(trusted))
    else { return false; };
    candidate.iter().zip(trusted).all(|(actual, expected)| actual == &expected)
}

pub(crate) fn verify(descriptor_bytes: &[u8], binding_bytes: &[u8]) -> Result<(), Error> {
    if parse_descriptor_v1(descriptor_bytes).is_none() {
        return Err(Error::DescriptorRejected("submitted descriptor is not a canonical bounded Descriptor v1"));
    }
    if !descriptor_fields_replay(descriptor_bytes, TRUSTED_DESCRIPTOR_BYTES) {
        return Err(Error::DescriptorRejected(
            "submitted descriptor fields do not replay the trusted value this consumer was generated from",
        ));
    }
    if binding_bytes != TRUSTED_BINDING_BYTES {
        return Err(Error::ProviderMismatch(
            "submitted provider-binding bytes do not replay the trusted value this consumer was generated from",
        ));
    }
    Ok(())
}
"#;

