#[test]
fn open_rejects_a_mutated_descriptor_before_any_native_allocation() {
    let mut mutated = TRUSTED_DESCRIPTOR_BYTES.to_vec();
    mutated[0] ^= 0xff;
    let allocations_before = diagnostics::live_allocations();
    let error = Provider::open(&mutated, TRUSTED_BINDING_BYTES).unwrap_err();
    assert!(matches!(error, Error::DescriptorRejected(_)));
    assert_eq!(diagnostics::live_allocations(), allocations_before);
}

#[test]
fn open_rejects_a_mutated_binding_before_any_native_allocation() {
    let mut mutated = TRUSTED_BINDING_BYTES.to_vec();
    let last = mutated.len() - 1;
    mutated[last] ^= 0xff;
    let allocations_before = diagnostics::live_allocations();
    let error = Provider::open(TRUSTED_DESCRIPTOR_BYTES, &mutated).unwrap_err();
    assert!(matches!(error, Error::ProviderMismatch(_)));
    assert_eq!(diagnostics::live_allocations(), allocations_before);
}

#[test]
fn open_rejects_a_valid_binding_that_names_a_different_descriptor() {
    // The trusted binding is well-formed on its own, but paired against a
    // descriptor it was never generated for; this consumer's own replay (a
    // byte-exact pairing, not a semantic re-derivation) rejects it exactly
    // like a genuinely corrupted descriptor would.
    let mut different_descriptor = TRUSTED_DESCRIPTOR_BYTES.to_vec();
    different_descriptor.extend_from_slice(b"-a-different-but-well-formed-descriptor");
    let error = Provider::open(&different_descriptor, TRUSTED_BINDING_BYTES).unwrap_err();
    assert!(matches!(error, Error::DescriptorRejected(_)));
}

/// Every logical trace ordinal 0..=13 (`SPX_PG_TRACE_FRAME_VALIDATED`
/// through `SPX_PG_TRACE_CARRIER_RELEASE`; ordinal 14, the settlement call
/// itself, has nothing left to abort -- see `spx_pg_v1.h`) settles as a
/// failure with zero live native allocations/handles afterward, exactly like
/// `tests/public_generic_native_adapter_v1/probe.c`'s own C-hosted matrix
/// for the same provider.
#[test]
fn failure_injection_matrix_settles_every_ordinal_with_zero_live_resources() {
    for ordinal in 0u32..=13 {
        let mut provider =
            Provider::open(TRUSTED_DESCRIPTOR_BYTES, TRUSTED_BINDING_BYTES).expect("open");
        diagnostics::inject_failure(ordinal);
        let result = provider.transform(sample_input());
        assert!(result.is_err(), "ordinal {ordinal} must fail, got {result:?}");
        diagnostics::clear_failure_injection();
        assert_eq!(
            diagnostics::live_handles(&provider),
            0,
            "ordinal {ordinal} left a live handle on its provider"
        );
        drop(provider);
        assert_eq!(
            diagnostics::live_allocations(),
            0,
            "ordinal {ordinal} left a live native allocation"
        );
    }
}
